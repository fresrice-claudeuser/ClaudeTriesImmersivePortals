#!/usr/bin/env python3
"""
Wave-2 port stage. Runs LAST in tools/import_wave.sh (after overlays, codemods, port_sites, port_patches).

  1. tools/port_sites2.json  - position-driven fixes (generated by tools/gen_sites2.py from a real build.log; every
                               replacement verified with `inspect`). Same contract as port_sites.py (marker, exit 1 on mismatch).
  2. RULES2                  - global renames for classes that MOVED (verified with `inspect`).
  3. Cloth-free config       - IPConfig/IPGlobal/IPModMain/IPConfigGUI no longer use Cloth Config / AutoConfig.
  4. tools/deferred.txt      - upstream files that do not compile yet are removed (and unregistered from the mixin
                               json files) until their wave; a deleted mixin is simply not active, nothing crashes.

    python3 tools/port_wave2.py [repo-root]
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else ".").resolve()
BASE = ROOT / "src/main/java"
MARK = "// [tools/port_wave2.py: sites applied]"

RULES2 = [
    # (introduced in, description, regex, replacement)
    ("1.21.11", "net.minecraft.Util moved to net.minecraft.util.Util (inspect)", r"\bimport net\.minecraft\.Util;", "import net.minecraft.util.Util;"),
    ("1.21.2", "AbstractMinecart moved to ...vehicle.minecart (inspect)", r"net\.minecraft\.world\.entity\.vehicle\.AbstractMinecart\b", "net.minecraft.world.entity.vehicle.minecart.AbstractMinecart"),
    ("1.21.5", "AbstractArrow moved to ...projectile.arrow (inspect)", r"net\.minecraft\.world\.entity\.projectile\.AbstractArrow\b", "net.minecraft.world.entity.projectile.arrow.AbstractArrow"),
    ("1.21.5", "ThrownEnderpearl moved to ...projectile.throwableitemprojectile (inspect)", r"net\.minecraft\.world\.entity\.projectile\.ThrownEnderpearl\b", "net.minecraft.world.entity.projectile.throwableitemprojectile.ThrownEnderpearl"),
    ("1.21.2", "RelativeMovement was renamed Relative (inspect: net.minecraft.world.entity.Relative)", r"\bRelativeMovement\b", "Relative"),
    ("1.21.2", "DimensionTransition was renamed TeleportTransition (inspect: ...level.portal.TeleportTransition)", r"\bDimensionTransition\b", "TeleportTransition"),
    ("1.21.11", "ResourceKey::location method reference -> ::identifier (inspect)", r"\bResourceKey::location\b", "ResourceKey::identifier"),
    ("1.21.11", "FriendlyByteBuf::readResourceLocation -> ::readIdentifier (inspect)", r"::readResourceLocation\b", "::readIdentifier"),
    ("1.21.11", "FriendlyByteBuf::writeResourceLocation -> ::writeIdentifier (inspect)", r"::writeResourceLocation\b", "::writeIdentifier"),
]


def apply_sites2() -> int:
    data = json.loads((ROOT / "tools/port_sites2.json").read_text(encoding="utf-8"))
    fails = 0
    done = applied = 0
    for rel, spec in sorted(data["files"].items()):
        path = BASE / rel
        if not path.exists():
            continue  # deferred / not imported
        text = path.read_text(encoding="utf-8")
        if MARK in text:
            done += 1
            continue
        lines = text.split("\n")
        bad = None
        for h in sorted(spec["hunks"], key=lambda h: -h["line"]):
            a = h["line"] - 1
            if lines[a:a + len(h["old"])] != h["old"]:
                bad = h["line"]
                break
            lines[a:a + len(h["old"])] = h["new"]
        if bad is not None:
            print(f"  FAIL sites2 {rel}: old text differs at line {bad}")
            fails += 1
            continue
        for imp in spec.get("imports", []):
            stmt = f"import {imp};"
            if stmt not in lines:
                i = next((k for k, l in enumerate(lines) if l.startswith("package ")), -1)
                lines.insert(i + 1, stmt)
        path.write_text("\n".join(lines).rstrip("\n") + "\n" + MARK + "\n", encoding="utf-8")
        applied += 1
    print(f"wave2 sites: {applied} patched, {done} already done, {fails} failed")
    return fails


def global_rules() -> None:
    n = 0
    for p in sorted(BASE.rglob("*.java")):
        t = p.read_text(encoding="utf-8")
        new = t
        for _v, _d, rx, rep in RULES2:
            new = re.sub(rx, rep, new)
        if new != t:
            p.write_text(new, encoding="utf-8")
            n += 1
    print(f"wave2 rules: {n} file(s) touched")


def edit(rel: str, fn) -> None:
    p = BASE / rel
    if not p.exists():
        print(f"  (skip, missing) {rel}")
        return
    t = p.read_text(encoding="utf-8")
    new = fn(t)
    if new != t:
        p.write_text(new, encoding="utf-8")


IPCONFIG_HOLDER = '''
    private static IPConfig instance;

    private static java.nio.file.Path configPath() {
        return net.fabricmc.loader.api.FabricLoader.getInstance().getConfigDir().resolve("immersive_portals.json");
    }

    // Cloth Config / AutoConfig are not used in this port: plain Gson file; the Mod Menu screen is dev.claudeportals.client.ConfigScreen.
    public static IPConfig getConfig() {
        if (instance == null) {
            IPConfig loaded = null;
            try {
                java.nio.file.Path path = configPath();
                if (java.nio.file.Files.exists(path)) {
                    loaded = new com.google.gson.Gson().fromJson(java.nio.file.Files.readString(path), IPConfig.class);
                }
            }
            catch (Exception e) {
                Helper.err("Failed to read Immersive Portals config, using defaults: " + e);
            }
            instance = loaded != null ? loaded : new IPConfig();
        }
        return instance;
    }

    public void saveConfigFile() {
        instance = this;
        try {
            java.nio.file.Files.writeString(
                configPath(),
                new com.google.gson.GsonBuilder().setPrettyPrinting().create().toJson(this)
            );
        }
        catch (Exception e) {
            Helper.err("Failed to save Immersive Portals config: " + e);
        }
        onConfigChanged();
    }
'''


def ipconfig(t: str) -> str:
    t = re.sub(r"^import me\.shedaniel[^\n]*\n", "", t, flags=re.M)
    t = re.sub(r"^[ \t]*@ConfigEntry[^\n]*\n", "", t, flags=re.M)
    t = re.sub(r"^@Config\([^\n]*\)\n", "", t, flags=re.M)
    t = t.replace(" implements ConfigData", "")
    t = re.sub(r"\n    public static IPConfig getConfig\(\) \{.*?\n    \}\n\s*\n    public void saveConfigFile\(\) \{.*?\n    \}\n",
               IPCONFIG_HOLDER, t, flags=re.S)
    return t


def hover(t: str) -> str:
    """Item.appendHoverText(ItemStack, TooltipContext, TooltipDisplay, Consumer<Component>, TooltipFlag) (inspect)."""
    m = re.search(r"List<Component> (\w+), TooltipFlag tooltipFlag\n(\s*)\) \{\n(\s*)super\.appendHoverText\((\w+), tooltipContext, \1, tooltipFlag\);", t)
    if not m:
        return t
    v = m.group(1)
    t = t[:m.start()] + (f"TooltipDisplay display, Consumer<Component> {v}, TooltipFlag tooltipFlag\n{m.group(2)}) {{\n"
                         f"{m.group(3)}super.appendHoverText({m.group(4)}, tooltipContext, display, {v}, tooltipFlag);") + t[m.end():]
    t = re.sub(r"\b" + v + r"\.add\(", v + ".accept(", t)
    t = t.replace("\nimport ", "\nimport net.minecraft.world.item.component.TooltipDisplay;\nimport java.util.function.Consumer;\nimport ", 1)
    return t


def cloth_free() -> None:
    core = "qouteall/imm_ptl/core/"
    edit(core + "platform_specific/IPConfig.java", ipconfig)
    edit(core + "IPGlobal.java", lambda t: re.sub(r"^import me\.shedaniel[^\n]*\n", "", t, flags=re.M)
         .replace("    public static ConfigHolder<IPConfig> configHolder;\n", ""))

    def main_(t: str) -> str:
        t = re.sub(r"^import me\.shedaniel[^\n]*\n", "", t, flags=re.M)
        return re.sub(r"        IPGlobal\.configHolder = AutoConfig\.register.*?\n        \}\);\n", "", t, flags=re.S)
    edit(core + "IPModMain.java", main_)
    edit(core + "platform_specific/IPConfigGUI.java", lambda t: re.sub(r"^import me\.shedaniel[^\n]*\n", "", t, flags=re.M)
         .replace("return AutoConfig.getConfigScreen(IPConfig.class, parent).get();", "return new dev.claudeportals.client.ConfigScreen(parent);"))
    p = BASE / (core + "platform_specific/IPModMenuConfigEntry.java")
    if p.exists():
        p.unlink()  # our Mod Menu entry is dev.claudeportals.client.ClaudePortalsModMenu


def api_patches() -> None:
    for rel in ("qouteall/imm_ptl/peripheral/CommandStickItem.java", "qouteall/imm_ptl/peripheral/PortalHelperItem.java",
                "qouteall/imm_ptl/peripheral/wand/PortalWandItem.java"):
        edit(rel, hover)


def defer() -> None:
    lst = ROOT / "tools/deferred.txt"
    gone = []
    for raw in lst.read_text(encoding="utf-8").splitlines():
        raw = raw.split("#")[0].strip()
        if not raw:
            continue
        p = BASE / raw
        if p.exists():
            p.unlink()
        gone.append(raw)
    # unregister deleted mixins (compare fully qualified class names, per json package)
    fq = {g[:-5].replace("/", ".") for g in gone}
    for jf in (ROOT / "src/main/resources").glob("*.mixins.json"):
        try:
            data = json.loads(jf.read_text(encoding="utf-8"))
        except Exception:
            continue
        pkg = data.get("package", "")
        changed = False
        for key in ("mixins", "client", "server"):
            if key in data:
                keep = [m for m in data[key] if f"{pkg}.{m}" not in fq]
                if len(keep) != len(data[key]):
                    data[key] = keep
                    changed = True
        if changed:
            jf.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
    print(f"wave2 deferred: {len(gone)} file(s) removed")


def main() -> int:
    fails = apply_sites2()
    global_rules()
    cloth_free()
    api_patches()
    defer()
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main())
