#!/usr/bin/env python3
"""
Applies the site-specific API fixes in tools/port_sites.json to the freshly imported upstream sources,
then runs LATE_RULES (global renames). Generated by tools/gen_sites.py from a real build.log; every hunk
is verified against the exact old lines (upstream is archived, so they cannot drift). A file whose old lines
do not match is left untouched and the script exits 1 at the end (same contract as port_patches.py).

    python3 tools/port_sites.py [repo-root]
"""
import json
import pathlib
import re
import sys

MARK = "// [tools/port_sites.py: applied]"

# Global renames that are unambiguous (the old name exists on exactly one Minecraft type). Run AFTER the sites,
# because the sites' recorded lines are the text before these renames.
LATE_RULES = [
    # (introduced in, description, regex, replacement)
    ("1.21.11", "FriendlyByteBuf.writeResourceLocation -> writeIdentifier (verified with inspect)",
     r"\.writeResourceLocation\(", ".writeIdentifier("),
    ("1.21.11", "FriendlyByteBuf.readResourceLocation -> readIdentifier (verified with inspect)",
     r"\.readResourceLocation\(", ".readIdentifier("),
    ("1.21.2", "RegistryAccess.registryOrThrow -> lookupOrThrow (verified with inspect)",
     r"\.registryOrThrow\(", ".lookupOrThrow("),
]


def add_import(lines, imp):
    stmt = f"import {imp};"
    if stmt in lines:
        return
    for i, ln in enumerate(lines):
        if ln.startswith("package "):
            lines.insert(i + 1, stmt)
            return
    lines.insert(0, stmt)


def main() -> int:
    root = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else ".")
    data = json.loads((root / "tools/port_sites.json").read_text(encoding="utf-8"))
    base = root / "src/main/java"
    failures, applied, missing, done = [], 0, 0, 0
    for rel, spec in sorted(data["files"].items()):
        path = base / rel
        if not path.exists():
            missing += 1
            continue
        text = path.read_text(encoding="utf-8")
        if MARK in text:
            done += 1
            continue
        lines = text.split("\n")
        bad = None
        for h in sorted(spec["hunks"], key=lambda h: -h["line"]):
            a = h["line"] - 1
            if lines[a:a + len(h["old"])] != h["old"]:
                bad = h["line"]
                break
            lines[a:a + len(h["old"])] = h["new"]
        if bad is not None:
            failures.append(f"{rel}: old text differs at line {bad}")
            continue
        for imp in spec.get("imports", []):
            add_import(lines, imp)
        path.write_text("\n".join(lines).rstrip("\n") + "\n" + MARK + "\n", encoding="utf-8")
        applied += 1
    late = 0
    for p in sorted(base.rglob("*.java")):
        t = p.read_text(encoding="utf-8")
        n = t
        for _v, _d, rx, rep in LATE_RULES:
            n = re.sub(rx, rep, n)
        if n != t:
            p.write_text(n, encoding="utf-8")
            late += 1
    print(f"port_sites: {applied} file(s) patched, {done} already done, {missing} not present, "
          f"{late} file(s) touched by late rules, {len(failures)} failure(s)")
    for f in failures:
        print("  FAIL", f)
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
